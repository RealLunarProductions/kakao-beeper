#!/usr/bin/env bash
# Run the KakaoTalk -> Beeper bridge in the foreground.
# First run: logs bbctl in (if needed), registers sh-kakaotalk with Beeper and
# writes the config to $KAKAO_BEEPER_DATA (default ~/.local/share/kakao-beeper).
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
data="${KAKAO_BEEPER_DATA:-$HOME/.local/share/kakao-beeper}"
mkdir -p "$data"
cd "$data"

# bbctl whoami exits 0 even when logged out, so check its output instead.
if bbctl whoami 2>&1 | grep -qi "not logged in"; then
    echo "== Logging bbctl in to Beeper"
    bbctl login
    if bbctl whoami 2>&1 | grep -qi "not logged in"; then
        echo "bbctl login did not complete; aborting." >&2
        exit 1
    fi
fi

# A config generated by bbctl targets Beeper's hungryserv. Anything else (e.g. the
# bridge's own defaults left over from a failed first run) is moved aside.
if [ -f config.yaml ] && ! grep -q 'software: hungry' config.yaml; then
    broken="config.yaml.broken-$(date +%Y%m%d-%H%M%S)"
    echo "== config.yaml isn't a Beeper config; moving it to $broken"
    mv config.yaml "$broken"
fi

if [ ! -f config.yaml ]; then
    echo "== Registering sh-kakaotalk with Beeper and generating config.yaml"
    # bbctl (urfave/cli) needs all flags before the bridge name.
    bbctl config --type bridgev2 -o config.yaml.new sh-kakaotalk
    if ! grep -q 'software: hungry' config.yaml.new 2>/dev/null; then
        echo "bbctl config did not produce a Beeper config; aborting." >&2
        rm -f config.yaml.new
        exit 1
    fi
    mv config.yaml.new config.yaml
fi

if ! grep -q '^network:' config.yaml; then
    cat >>config.yaml <<EOF

# Network-specific config options
network:
    node_path: $(command -v node)
    sidecar_script: $here/sidecar/sidecar.mjs
    state_dir: $data/agent-messenger
    initial_backfill: 30
EOF
fi

if [ ! -d "$here/sidecar/node_modules" ]; then
    npm install --prefix "$here/sidecar" --ignore-scripts --no-audit --no-fund
fi
if [ ! -x "$here/mautrix-kakaotalk" ]; then
    (cd "$here" && go build -tags goolm -o mautrix-kakaotalk ./cmd/mautrix-kakaotalk)
fi

echo "== Starting bridge (Ctrl+C to stop). In Beeper, DM @sh-kakaotalkbot:beeper.local and send: login"
exec "$here/mautrix-kakaotalk" -c config.yaml
